import type { GeoPoint } from "@/server/delivery/types";

const EARTH_RADIUS_KM = 6371;

/** Great-circle distance in km. Good enough for quote estimation and tests; production "nearby" search runs the equivalent PostGIS calculation server-side (see DATABASE.md). */
export function haversineDistanceKm(a: GeoPoint, b: GeoPoint): number {
  const toRad = (deg: number) => (deg * Math.PI) / 180;
  const dLat = toRad(b.latitude - a.latitude);
  const dLon = toRad(b.longitude - a.longitude);
  const lat1 = toRad(a.latitude);
  const lat2 = toRad(b.latitude);

  const h = Math.sin(dLat / 2) ** 2 + Math.sin(dLon / 2) ** 2 * Math.cos(lat1) * Math.cos(lat2);

  return 2 * EARTH_RADIUS_KM * Math.asin(Math.sqrt(h));
}
